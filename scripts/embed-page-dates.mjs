#!/usr/bin/env node
//
// Generates `web/lib/pageDates.generated.ts` — every public route and when it
// last actually changed, taken from git.
//
// **What it fixes.** `sitemap.ts` used to stamp every route with
// `new Date()`. That is the *build* time, not the page's, so every deploy told
// crawlers that all seven pages had changed simultaneously — including ones
// untouched for weeks. Search engines treat an obviously-wrong `lastmod` as
// noise and stop reading it, which costs the signal on the pages where it is
// true. A page's real last-changed date is a fact git already holds; this
// reads it rather than inventing one.
//
// **The route list is discovered, not typed here.** An earlier version carried
// a hand-written route → files map, which meant adding a page silently
// produced no entry and dropping one left a stale entry behind. Both were
// reproduced. `public-routes.mjs` walks the filesystem instead; see the
// reasoning there.
//
// **Why generated at build rather than read at request time.** Same reason as
// `embed-legal.mjs` and `embed-migrations.mjs`: a Vercel function bundle has
// no git directory and no repo paths, so anything computed from git has to be
// computed here, while the repo still exists, and baked in.
//
// **When git is unavailable it emits nothing rather than a guess.** A shallow
// clone, a source tarball, or a CI checkout without history all produce no
// date, and `sitemap.ts` then omits `lastModified` for that route. An absent
// `lastmod` is honest and simply unused; a fabricated one is the bug above.

import { writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { publicRoutes, SITEMAP_EXCLUDED } from "./public-routes.mjs";

const run = promisify(execFile);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Committer date of the last commit touching `file`, or null. */
async function lastCommitted(file) {
  try {
    const { stdout } = await run("git", ["log", "-1", "--format=%cI", "--", file], { cwd: ROOT });
    const iso = stdout.trim();
    return iso.length > 0 ? iso : null;
  } catch {
    // No git, no history, or the file is untracked. Caller treats this as
    // "unknown", never as "now".
    return null;
  }
}

const routes = (await publicRoutes()).filter((r) => !SITEMAP_EXCLUDED.has(r.route));

const entries = [];
let known = 0;
for (const { route, sources } of routes) {
  const dates = (await Promise.all(sources.map(lastCommitted))).filter(Boolean);
  // The newest of the contributing files: a page is as fresh as its freshest
  // part.
  const newest = dates.sort().at(-1) ?? null;
  if (newest) known++;
  entries.push(`  { route: ${JSON.stringify(route)}, lastModified: ${newest ? JSON.stringify(newest) : "null"} },`);
}

const source = `// GENERATED by scripts/embed-page-dates.mjs — do not edit.
//
// Every public route under \`app/(site)\`, discovered from the filesystem, with
// the date it last changed according to git. \`null\` means git could not tell
// us, and \`sitemap.ts\` then omits the date rather than substituting the build
// time. Regenerated by \`npm run build\`.

export interface PublicRoute {
  route: string;
  lastModified: string | null;
}

export const PUBLIC_ROUTES: PublicRoute[] = [
${entries.join("\n")}
];
`;

await writeFile(path.join(ROOT, "web", "lib", "pageDates.generated.ts"), source, "utf-8");
console.log(
  `embed-page-dates: ${routes.length} public route(s) discovered, ${known} dated from git → web/lib/pageDates.generated.ts`
);
