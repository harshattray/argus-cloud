#!/usr/bin/env node
//
// Generates `web/lib/imageSizes.generated.ts` — the intrinsic size of every
// screenshot the site serves, and whether a `.webp` was generated beside it.
//
// **What it fixes.** Every `<img>` on the site was written without `width` or
// `height`. A browser cannot reserve space for an image whose size it will not
// learn until the bytes arrive, so each one landed by pushing the text below it
// down the page — the reader loses their place, and it is measured as
// Cumulative Layout Shift. The fix is to state the intrinsic size in the
// markup; the reason it was not done is that it means writing two numbers per
// image and keeping them right when a screenshot is retaken.
//
// So they are not written by hand. This reads the real pixel dimensions out of
// the PNG headers at build time, which makes a wrong number impossible rather
// than unlikely — the same reason `embed-page-dates.mjs` reads git rather than
// letting anyone type a date.
//
// **It also records which images have a `.webp`.** `optimise-screenshots.mjs`
// writes one beside each PNG, but it needs `cwebp` and so runs by hand, not on
// every build. Reading the directory here means the components offer the WebP
// exactly when it is really there — a newly added screenshot whose `.webp` has
// not been generated yet renders correctly from its PNG instead of 404ing at a
// file that was assumed to exist.
//
// Dimensions come from the PNG, never the WebP, and that is safe because the
// optimiser re-encodes at full size and never resizes. If it ever gains a
// resize step, this assumption has to be revisited or the two files will
// disagree about their own shape.

import { readdir, readFile, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = path.join(ROOT, "web", "public");

/** Kept in step with `optimise-screenshots.mjs` — same directories, same reason. */
const DIRS = ["screens", "cases"];

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

/**
 * Width and height from a PNG's IHDR chunk, or null if the file is not a PNG.
 *
 * IHDR is mandatory and must be the first chunk, so the two dimensions are
 * always at a fixed offset: 8 bytes of signature, 4 of chunk length, 4 of chunk
 * type, then width and height as big-endian uint32s.
 */
function pngSize(buffer) {
  if (buffer.length < 24 || !buffer.subarray(0, 8).equals(PNG_SIGNATURE)) return null;
  if (buffer.subarray(12, 16).toString("ascii") !== "IHDR") return null;
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
}

async function pngsUnder(dir) {
  const out = [];
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await pngsUnder(full)));
    else if (entry.name.toLowerCase().endsWith(".png")) out.push(full);
  }
  return out;
}

const exists = async (file) => {
  try {
    await stat(file);
    return true;
  } catch {
    return false;
  }
};

const entries = [];
let withWebp = 0;

for (const dir of DIRS) {
  for (const png of (await pngsUnder(path.join(PUBLIC, dir))).sort()) {
    const size = pngSize(await readFile(png));
    if (!size) {
      // A file named .png that is not one. Say so rather than emit a guess —
      // a wrong width is worse than an absent one, which simply falls back to
      // the old unsized behaviour for that image alone.
      console.warn(`embed-image-sizes: ${path.relative(PUBLIC, png)} is not a readable PNG, skipped`);
      continue;
    }
    const url = "/" + path.relative(PUBLIC, png).split(path.sep).join("/");
    const webp = await exists(png.replace(/\.png$/i, ".webp"));
    if (webp) withWebp++;
    entries.push(
      `  ${JSON.stringify(url)}: { width: ${size.width}, height: ${size.height}, webp: ${webp} },`
    );
  }
}

const source = `// GENERATED by scripts/embed-image-sizes.mjs — do not edit.
//
// The intrinsic pixel size of every screenshot under \`public/\`, read from the
// PNG headers, plus whether \`optimise-screenshots.mjs\` has written a \`.webp\`
// beside it. Regenerated by \`npm run build\`.
//
// Consumed by the \`Shot\` and \`Annotated\` components so that no \`<img>\` on the
// site is written without a width and a height, and so the WebP is offered
// only when it exists.

export interface ImageAsset {
  width: number;
  height: number;
  webp: boolean;
}

export const IMAGE_SIZES: Record<string, ImageAsset | undefined> = {
${entries.join("\n")}
};
`;

await writeFile(path.join(ROOT, "web", "lib", "imageSizes.generated.ts"), source, "utf-8");
console.log(
  `embed-image-sizes: ${entries.length} image(s) measured, ${withWebp} with a .webp → web/lib/imageSizes.generated.ts`
);
