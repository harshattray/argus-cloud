#!/usr/bin/env node
//
// Generates `src/migrations.generated.ts` — every migration's SQL, embedded as
// a string constant.
//
// **Why this exists.** `migrate()` used to `readdir("<dist/db.js>/../migrations")`
// at runtime. That is a computed path across a workspace symlink, and it
// resolved to different places in a local build and in a Vercel function
// bundle. The deployed site failed on its first database request with
// `ENOENT: scandir '/vercel/path0/migrations'` while every local build stayed
// green — the same class of failure `FinishedSPEC.md` §4f already recorded once
// (0 of 34 bundles carried the .sql files). Fixing it with a second path guess
// would have been the third round of the same argument.
//
// Embedded SQL cannot be lost by a bundler, a symlink, or a host's idea of the
// working directory. The files on disk stay the source of truth; this is a
// build artifact, regenerated by `npm run build` and never committed.
//
// `migrations.test.mjs` M8 asserts the generated module matches the directory
// byte for byte, so a stale copy fails the suite rather than production.

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS = path.join(ROOT, "migrations");
const OUT = path.join(ROOT, "src", "migrations.generated.ts");

const files = (await readdir(MIGRATIONS)).filter((f) => f.endsWith(".sql")).sort();

const entries = [];
for (const file of files) {
  const sql = await readFile(path.join(MIGRATIONS, file), "utf-8");
  entries.push(`  { name: ${JSON.stringify(file)}, sql: ${JSON.stringify(sql)} },`);
}

const source = `// GENERATED by scripts/embed-migrations.mjs — do not edit.
//
// Regenerated by \`npm run build\`. Edit the .sql files in migrations/ instead.

export interface EmbeddedMigration {
  name: string;
  sql: string;
}

export const EMBEDDED_MIGRATIONS: EmbeddedMigration[] = [
${entries.join("\n")}
];
`;

await writeFile(OUT, source, "utf-8");
console.log(`embed-migrations: ${files.length} migration(s) → src/migrations.generated.ts`);
